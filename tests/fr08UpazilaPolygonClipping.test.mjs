import assert from 'node:assert/strict';
import fs from 'node:fs';
import { selectUpazilaBoundary, clipResearchCells, clipRainCells } from '../frontend/src/upazilaPolygonOverlay.js';
const read = name => JSON.parse(fs.readFileSync(new URL(`../frontend/public/data/${name}`, import.meta.url), 'utf8'));
const boundaries = read('haorshield_upazila_boundaries.geojson');
const clips = read('haorshield_upazila_cell_clips.json');
const flood = read('haorshield_sar_future_candidates.geojson');
const rain = read('haorshield_rainfall_risk.geojson');
assert.equal(flood.features.length, 306);
const chhatak = selectUpazilaBoundary(boundaries,'Sunamganj','Chhatak');
assert.ok(chhatak && chhatak.features.length === 1);
assert.equal(chhatak.features[0].properties.name,'Chhatak');
const a = clipResearchCells(flood.features,clips,'Sunamganj','Chhatak');
const b = clipRainCells(rain.features,clips,'Sunamganj','Chhatak');
assert.ok(a.length > 0 && b.length > 0);
assert.ok(a.length < 306 && b.length < 306);
assert.ok(a.every(f => f.properties.overlapFraction > 0 && f.properties.overlapFraction <= 1));
assert.deepEqual(clipResearchCells(flood.features,clips,'Sunamganj','NotARealUpazila'),[]);
assert.deepEqual(clipRainCells(rain.features,clips,'Sunamganj','NotARealUpazila'),[]);
assert.equal(clipResearchCells(flood.features,clips,'Sunamganj',null).length,306);
assert.deepEqual(clipRainCells(rain.features,{...clips,source_cell_count:305},'Sunamganj','Chhatak'),[]);
const map = fs.readFileSync(new URL('../frontend/src/LandAttentionMap.jsx', import.meta.url),'utf8');
const rainSource = fs.readFileSync(new URL('../frontend/src/SimpleRainMap.jsx', import.meta.url),'utf8');
const checker = fs.readFileSync(new URL('../frontend/src/FloodRiskChecker.jsx', import.meta.url),'utf8');
assert.doesNotMatch(map,/L\.circle\(point[^\n]*getBounds/);
assert.match(map,/clipResearchCells/);
assert.match(rainSource,/clipRainCells/);
assert.match(checker,/selectedUpazila=\{result\.selectedUpazila\}/);
console.log('PASS real Chhatak boundary, both clipped datasets, no fallback, and no Circle.getBounds crash');


import assert from 'node:assert/strict';
import {farmerHorizon, farmerSummary, riverStatusExplanation} from '../frontend/src/farmerOutlookView.js';
for (const hours of [24,48,72]) {
  const base={horizonHours:hours,rank:null,riverAvailable:false,rainfallAvailable:true};
  const rain={horizonHours:hours,complete:true,rainfallMm:0};
  let view=farmerHorizon(base,rain,'No nearby modeled river cell (within 8 km)');
  assert.match(view.title,/cannot be fully assessed/i);
  assert.match(view.detail,/No suitable modeled river cell/);
  assert.match(view.detail,/cannot be ruled out/i);
  assert.match(view.action,/official river alerts/i);
  assert.equal(view.rainText,'0.0 mm rain forecast');
  assert.equal(view.uncertain,true);
  view=farmerHorizon(base,{horizonHours:hours,complete:false,rainfallMm:null});
  assert.match(view.title,/cannot be assessed/);
  assert.match(view.rainText,/unavailable/);
  view=farmerHorizon({...base,rank:3},rain);
  assert.match(view.title,/High flood concern/);
  assert.match(view.action,/official/);
  view=farmerHorizon({...base,rank:2},rain);
  assert.match(view.detail,/incomplete/);
  view=farmerHorizon({...base,rank:0,riverAvailable:true,riverIdentityVerified:false},rain);
  assert.match(view.detail,/not been confirmed/);
  assert.equal(view.uncertain,true);
  view=farmerHorizon({...base,rank:0,riverAvailable:true,riverIdentityVerified:true},rain);
  assert.equal(view.uncertain,false);
  view=farmerHorizon({...base,rank:0,riverAvailable:true},{horizonHours:hours,complete:false,rainfallMm:null});
  assert.match(view.title,/cannot be fully assessed/);
}
assert.match(riverStatusExplanation('three-day river forecast for forecast date unavailable'),/matching|match this period/);
assert.match(riverStatusExplanation('Hydrological service returned 503'),/service/);
assert.match(farmerSummary([{rainfallAvailable:true,riverAvailable:false}],null,'No nearby modeled river cell (within 8 km)').lines.join(' '),/No suitable modeled river cell/);
console.log('FR-18: forecast clarity and partial-data safety tests passed');

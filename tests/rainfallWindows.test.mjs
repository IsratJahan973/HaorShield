import assert from 'node:assert/strict';
import {rollingRainfallWindows} from '../frontend/src/rainfallWindows.js';
const start=new Date('2026-10-16T10:30:00Z');
const full=Array.from({length:72},(_,i)=>({timestamp:new Date(start.getTime()+(i+0.5)*3600000),value:2,probability:40}));
const result=x=>rollingRainfallWindows(x,start);
assert.deepEqual(result(full).map(x=>x.complete),[true,true,true]);
assert.deepEqual(result(full).map(x=>x.rainfallMm),[48,96,144]);
assert.deepEqual(result(full).map(x=>x.rainChanceMax),[40,40,40]);
assert.deepEqual(result(full.slice(0,7)).map(x=>x.complete),[false,false,false]);
assert.deepEqual(result(full.slice(0,7)).map(x=>x.rainfallMm),[null,null,null]);
assert.deepEqual(result(full.filter((_,i)=>i!==12)).map(x=>x.complete),[false,false,false]);
assert.deepEqual(result([...full,full[5]]).map(x=>x.complete),[false,false,false]);
const missing=full.map((x,i)=>i===4?{...x,value:null}:x);
assert.deepEqual(result(missing).map(x=>x.complete),[false,false,false]);
const badChance=full.map((x,i)=>i===2?{...x,probability:null}:x);
assert.deepEqual(result(badChance).map(x=>x.rainChanceMax),[null,null,null]);
assert.deepEqual(result(full).map(x=>x.horizonHours),[24,48,72]);
console.log('PASS 10 rolling-rainfall completeness assertions');
